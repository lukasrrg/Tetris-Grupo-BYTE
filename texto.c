void caracterDibujar(const tCaracter *carac, tCursorTexto *cursor, int color)   //Dibuja un caracter a partir de darle un tCaracter como parámetro
{
    int i, j;
    const char *p;

    for (i = 0; i < carac->espaciado; i++)
    {
        for (j = 0; j < ALTO_ESTANDAR_LETRA; j++)
        {
            p = carac->matriz + (j*carac->espaciado + i);

            if (*p == 'X')
                gbt_dibujar_pixel(cursor->posX + i, cursor->posY + j, color);
        }
    }

    cursor->posX += carac->espaciado + ESPACIADO_ENTRE_LETRAS;    //Avanza el cursor en cierta cantidad para dar espacio a la siguiente letra (en caso de haber)
}

int obtenerIndice(char caracter)        //Si le das un char, devuelve el indice correspondiente del vector fuente
{
    if (caracter >= 'A' && caracter <= 'Z')
        return caracter - 'A';
    if (caracter >= 'a' && caracter <= 'z')
        return caracter - 'G';
    switch(caracter)                    //Completar para el resto de caracteres faltantes a medida que se vayan agregando
    {
        case ' ':
            return 26;
    }

    return 0;
}

void caracterDibujarChar(char carac, tCursorTexto *cursor, int color)     //Dibuja un caracter a partir de darle un char como parámetro
{
    int i, j;
    const tCaracter *caracter = &fuente1[obtenerIndice(carac)];
    const char *p;

    for (i = 0; i < caracter->espaciado; i++)
    {
        for (j = 0; j < ALTO_ESTANDAR_LETRA; j++)
        {
            p = caracter->matriz + (j*caracter->espaciado + i);

            if (*p == 'X')
                gbt_dibujar_pixel(cursor->posX + i, cursor->posY + j, color);
        }
    }

    cursor->posX += fuente1[obtenerIndice(carac)].espaciado + ESPACIADO_ENTRE_LETRAS;   //Avanza el cursor en cierta cantidad para dar espacio a la siguiente letra (en caso de haber)
}

void escribirTexto(const char str[], tCursorTexto *cursor, int color)
{
    const char *p;
    p = str;

    while(*p != '\0')
    {
        caracterDibujarChar(*p, cursor, color);
        p++;
    }
}

void caracterDibujarEscalado(char carac, tCursorTexto *cursor, int color, int escala)
{
    int i, j, ei, ej;
    const tCaracter *caracter = &fuente1[obtenerIndice(carac)];
    const char *p;

    for (i = 0; i < caracter->espaciado; i++) {
        for (j = 0; j < ALTO_ESTANDAR_LETRA; j++) {
            p = caracter->matriz + (j * caracter->espaciado + i);

            if (*p == 'X') {
                for(ei = 0; ei < escala; ei++) {
                    for(ej = 0; ej < escala; ej++) {
                        gbt_dibujar_pixel(cursor->posX + (i * escala) + ei,
                                          cursor->posY + (j * escala) + ej,
                                          color);
                    }
                }
            }
        }
    }
    cursor->posX += (caracter->espaciado + ESPACIADO_ENTRE_LETRAS) * escala;
}
