void caracterDibujar(const tCaracter *carac, tCursorTexto *cursor, int color)   //Dibuja un caracter a partir de darle un tCaracter como parámetro
{
    int i, j;
    const char *p;

    for (i = 0; i < carac->espaciado; i++)
    {
        for (j = 0; j < ALTO_ESTANDAR_LETRA; j++)
        {
            p = carac->matriz + (j*carac->espaciado + i);

            if (*p == 'X')
                gbt_dibujar_pixel(cursor->posX + i, cursor->posY + j, color);
        }
    }

    cursor->posX += carac->espaciado + ESPACIADO_ENTRE_LETRAS;    //Avanza el cursor en cierta cantidad para dar espacio a la siguiente letra (en caso de haber)
}

int obtenerIndice(char caracter)        //Si le das un char, devuelve el indice correspondiente del vector fuente
{
    if (caracter >= 'A' && caracter <= 'Z')
        return caracter - 'A';
    if (caracter >= 'a' && caracter <= 'z')
        return caracter - 71;
    if (caracter >= '0' && caracter <= '9')     //Si si pasa al numero como char
        return caracter - 21;
    if (caracter >= 0 && caracter <= 9)         //Si se pasa al numero como int
        return caracter + 27;
    switch(caracter)                    //Completar para el resto de caracteres faltantes a medida que se vayan agregando
    {
    case ' ':
        return 26;
        break;
    case ':':
        return 37;
    }

    return 0;
}

